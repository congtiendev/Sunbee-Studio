// Builds server/services/capcut/catalog.ts — CapCut's own clip animations,
// transitions and video effects (free ones only), as listed by VectCutAPI's
// pyJianYingDraft metadata (Apache-2.0, github.com/sun-guannan/VectCutAPI).
// CapCut downloads each by its resource/effect id when a draft uses it.
//
//   node scripts/build-capcut-catalog.mjs <path to pyJianYingDraft/metadata>
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) {
  console.error("usage: node scripts/build-capcut-catalog.mjs <pyJianYingDraft/metadata>");
  process.exit(1);
}

/** Python enum classes in a file: { ClassName: body }. */
function classes(file) {
  const text = readFileSync(join(dir, file), "utf8");
  const out = {};
  const re = /^class (\w+)\(Effect_enum\):([\s\S]*?)(?=^class |\s*$(?![\s\S]))/gm;
  for (const m of text.matchAll(re)) out[m[1]] = m[2];
  return out;
}

const str = String.raw`"((?:[^"\\]|\\.)*)"`;
const num = String.raw`(-?[\d.]+)`;
const bool = String.raw`(True|False)`;

/** `Name = Animation_meta("Title", vip, duration, "resource_id", "effect_id", "md5")` */
function animations(body, kind) {
  const re = new RegExp(String.raw`^\s+(\w+)\s*=\s*Animation_meta\(${str},\s*${bool},\s*${num},\s*${str},\s*${str},\s*${str}\)`, "gm");
  return [...body.matchAll(re)]
    .filter((m) => m[3] === "False")
    .map((m) => ({ key: `${kind}:${m[1]}`, name: m[2], durationMs: Math.round(Number(m[4]) * 1000), resourceId: m[5], effectId: m[6] }));
}

/** `Name = Transition_meta("Name", vip, "resource_id", "effect_id", "md5", duration, overlap)` */
function transitions(body) {
  const re = new RegExp(String.raw`^\s+(\w+)\s*=\s*Transition_meta\(${str},\s*${bool},\s*${str},\s*${str},\s*${str},\s*${num},\s*${bool}\)`, "gm");
  return [...body.matchAll(re)]
    .filter((m) => m[3] === "False")
    .map((m) => ({
      key: `transition:${m[1]}`,
      name: m[2],
      resourceId: m[4],
      effectId: m[5],
      durationMs: Math.round(Number(m[7]) * 1000),
      overlap: m[8] === "True",
    }));
}

/** `Name = Effect_meta("Name", vip, "resource_id", "effect_id", "md5", [Effect_param("n", default, min, max), …])` */
function effects(body, kind) {
  const re = new RegExp(String.raw`^\s+(\w+)\s*=\s*Effect_meta\(${str},\s*${bool},\s*${str},\s*${str},\s*${str}(?:,\s*\[([\s\S]*?)\])?\)`, "gm");
  const param = new RegExp(String.raw`Effect_param\(${str},\s*${num},\s*${num},\s*${num}\)`, "g");
  return [...body.matchAll(re)]
    .filter((m) => m[3] === "False")
    .map((m) => ({
      key: `${kind}:${m[1]}`,
      name: m[2],
      resourceId: m[4],
      effectId: m[5],
      params: [...(m[7] ?? "").matchAll(param)].map((p) => ({ name: p[1], default: Number(p[2]), min: Number(p[3]), max: Number(p[4]) })),
    }));
}

const anim = classes("capcut_animation_meta.py");
const trans = classes("capcut_transition_meta.py");
const fx = classes("capcut_effect_meta.py");

const catalog = {
  source: "VectCutAPI pyJianYingDraft metadata (Apache-2.0) — CapCut built-ins, free items only",
  intros: animations(anim.CapCut_Intro_type ?? "", "in"),
  outros: animations(anim.CapCut_Outro_type ?? "", "out"),
  combos: animations(anim.CapCut_Group_animation_type ?? "", "group"),
  transitions: transitions(trans.CapCut_Transition_type ?? ""),
  effects: [
    ...effects(fx.CapCut_Video_scene_effect_type ?? "", "scene"),
    ...effects(fx.CapCut_Video_character_effect_type ?? "", "character"),
  ],
};
// A TS module, not JSON: the server is bundled, and a module ships inside the bundle.
const out = "server/services/capcut/catalog.ts";
writeFileSync(
  out,
  "// Generated by scripts/build-capcut-catalog.mjs — do not edit by hand.\n" +
    'import type { CapcutCatalog } from "./catalog-types.js";\n\n' +
    `export const CAPCUT_CATALOG: CapcutCatalog = ${JSON.stringify(catalog, null, 1)};\n`,
);
console.log(
  `${out}: ${catalog.intros.length} intros, ${catalog.outros.length} outros, ${catalog.combos.length} combos, ` +
    `${catalog.transitions.length} transitions, ${catalog.effects.length} effects`,
);
